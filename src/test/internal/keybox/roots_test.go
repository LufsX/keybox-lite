func TestOfficialGoogleRootRecognition(t *testing.T) {
	for _, root := range officialGoogleRoots {
		t.Run(root.name, func(t *testing.T) {
			block, _ := pem.Decode([]byte(root.certificate))
			if block == nil {
				t.Fatal("invalid official root fixture")
			}
			cert, err := x509.ParseCertificate(block.Bytes)
			if err != nil {
				t.Fatal(err)
			}
			sum := sha256.Sum256(cert.RawSubjectPublicKeyInfo)
			fingerprint := hex.EncodeToString(sum[:])
			if fingerprint != root.fingerprint {
				t.Fatalf("SPKI fingerprint = %s, want %s", fingerprint, root.fingerprint)
			}
			if got := knownRootKeys[fingerprint]; got != "google" {
				t.Fatalf("root recognition = %q, want google", got)
			}

			// A recognized root must not make an unrelated private key valid.
			fixture := prepareFixtureFor(t, root.algorithm)
			fixture.certificate = root.certificate
			result := CheckIntegrity(prepareTestDocument(prepareTestKey(fixture, 1, "<NumberOfCertificates>1</NumberOfCertificates>")))
			if len(result.Keys) != 1 {
				t.Fatalf("expected one recognized root: %+v", result)
			}
			key := result.Keys[0]
			if key.Root != "google" || !key.ChainValid || !key.PrivateKeyValid || key.KeyMatch || result.Status != "invalid" {
				t.Fatalf("root recognition or integrity separation failed: %+v", result)
			}
		})
	}
}
