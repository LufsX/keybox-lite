export const supportedLanguages = [
  { code: "en", nativeLabel: "English" },
  { code: "zh", nativeLabel: "简体中文" },
  { code: "zh-TW", nativeLabel: "繁體中文" },
  { code: "ja", nativeLabel: "日本語" },
  { code: "ko", nativeLabel: "한국어" },
  { code: "es", nativeLabel: "Español" },
  { code: "ru", nativeLabel: "Русский" },
] as const

export type Locale = typeof supportedLanguages[number]["code"]

export function isLocale(value: unknown): value is Locale {
  return supportedLanguages.some(language => language.code === value)
}

export function resolveLocale(value: string): Locale {
  const parts = value.trim().replace(/_/g, "-").toLowerCase().split("-")
  const language = parts[0]
  if (language === "zh") {
    if (parts.includes("hant")) return "zh-TW"
    if (parts.includes("hans")) return "zh"
    return parts.some(part => ["tw", "hk", "mo"].includes(part)) ? "zh-TW" : "zh"
  }
  return isLocale(language) ? language : "en"
}

